// Repeat a public read-only Status only when the shared production
// RateBudget proves a LOCAL, NO-SEND private GET defer. The same captured
// financial sources and the same release owner remain authoritative.
async fn t09_6_status_after_local_read_defer(
    trade: &Arc<TradeService>,
    rate_budget: &RateBudget,
    feed: &Arc<crate::accounts::recorded_support::RecordedAccountHttp>,
    intent: &str,
    allowed_new_cancel_posts: usize,
    phase: &str,
) -> serde_json::Value {
    use okx_protocol::trading::TradeRequest;
    assert!(allowed_new_cancel_posts <= 1, "one protective cancel per Status");
    let until = std::time::Instant::now() + Duration::from_secs(15);
    let posts_before = feed.outbound_posts.lock().unwrap().len();
    loop {
        let result = tokio::time::timeout_at(
            until.into(),
            trade.trade(
                "fixture-a",
                &TradeRequest::Status { reference: intent.to_owned() },
                None,
            ),
        )
        .await
        .unwrap_or_else(|_| {
            // Preserve the first failing Status phase and the actual recorded
            // I/O frontier. This read-only diagnostic runs only on timeout;
            // it never extends the deadline, replays a POST or mutates SQL.
            // Release each transport lock before sampling the next one.
            let recent_gets = {
                let requests = feed.requests.lock().unwrap();
                requests.iter().rev().take(8).cloned().collect::<Vec<_>>()
            };
            let denied_routes = {
                let denied = feed.denied_routes.lock().unwrap();
                denied.iter().rev().take(8).cloned().collect::<Vec<_>>()
            };
            let posts_now = feed.outbound_posts.lock().unwrap().len();
            let diagnostic = serde_json::json!({
                "schema":"okx.t09-6-status-timeout/v1",
                "phase":phase,
                "intent":intent,
                "allowed_new_cancel_posts":allowed_new_cancel_posts,
                "outbound_posts_before":posts_before,
                "outbound_posts_now":posts_now,
                "recent_recorded_gets":recent_gets,
                "denied_recorded_routes":denied_routes,
                "unconsumed_required_gets":feed.unconsumed_reads(),
                "public_clock_deliveries":feed.public_clock_deliveries(),
                "last_private_throttle":format!("{:?}",rate_budget.snapshot().last_throttle),
            });
            panic!("T09_6_STATUS_TIMEOUT_V1:{phase}:{diagnostic}");
        });
        let posts_now = feed.outbound_posts.lock().unwrap().len();
        assert!(
            posts_now >= posts_before && posts_now <= posts_before + allowed_new_cancel_posts,
            "T09.6 Status must not create or repeat an unrelated venue POST: before={posts_before} now={posts_now} allowed_cancel={allowed_new_cancel_posts}"
        );
        let local_reason = match &result {
            Ok(status) => status["data"]["financial_error"]
                .as_str()
                .and_then(|e| e.strip_prefix("OKX API error: ")),
            Err(reason) => Some(reason.as_str()),
        };
        let remaining = until.saturating_duration_since(std::time::Instant::now());
        if let Some(delay) = local_reason.and_then(|reason| {
            recorded_preview_local_defer(reason, rate_budget, remaining)
        }) {
            // Only a typed LOCAL PrivateRestRead no-send defer authorizes
            // retrying this read-only Status. It may have consumed the one
            // raw venue /public/time page before that defer. Record a NEW,
            // finite external clock observation at this witnessed retry
            // boundary; never synthesize a clock in the HTTP GET handler,
            // repeat an exchange POST, or relax mutation_timing(5000).
            let deliveries_before = feed.public_clock_deliveries();
            tokio::time::timeout_at(until.into(), tokio::time::sleep(delay))
                .await
                .expect("T09.6 authorized read defer expired");
            let observed_at = chrono::Utc::now().timestamp_millis();
            let raw = serde_json::to_vec(&serde_json::json!({
                "code":"0", "msg":"", "data":[{"ts":observed_at.to_string()}]
            })).expect("recorded external clock wire");
            let retired = feed.advance_recorded_public_clock(raw);
            assert!(
                retired <= 1,
                "T09.6 retry cannot retire multiple unconsumed clock samples"
            );
            eprintln!(
                "T09_6_CLOCK_AFTER_LOCAL_READ_DEFER_V1:remaining_ms={} delivered_before={} delivered_now={} retired={} posts_before={} posts_now={}",
                until.saturating_duration_since(std::time::Instant::now()).as_millis(),
                deliveries_before,
                feed.public_clock_deliveries(),
                retired,
                posts_before,
                posts_now,
            );
            continue;
        }
        let status = result.unwrap_or_else(|reason| {
            panic!("T09_6_STATUS_NONLOCAL_ERROR:{intent}:{reason}")
        });
        assert_eq!(posts_now, posts_before + allowed_new_cancel_posts,
            "T09.6 confirmed exactly one cancel POST when cleanup is due, or zero for close readback");
        return status;
    }
}

